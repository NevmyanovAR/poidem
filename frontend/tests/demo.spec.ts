test('demo author, plan cards and match remain usable at mobile and desktop sizes', async ({ page }) => {
  test.setTimeout(90000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('https://telegram.org/js/telegram-web-app.js', route => route.fulfill({ status: 200, body: '' }))
  await enableDemo(page)
  await page.goto('/people/demo-gallery')
  await page.getByRole('button', { name: 'Пойдём?', exact: true }).click()
  await page.getByRole('button', { name: 'Имитировать принятие автором' }).click()
  const matchPath = new URL(page.url()).pathname
  for (const width of [320, 393, 768, 1440]) {
    await page.setViewportSize({ width, height: width === 320 ? 568 : 852 })
    for (const route of ['/catalog', '/people/demo-dinner', '/plans', matchPath]) {
      await page.goto(route, { waitUntil: 'domcontentloaded' })
      await page.evaluate(() => document.fonts.ready)
      expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), `${route} at ${width}`).toBe(false)
      await expect(page.locator('h1, h2').first()).toBeVisible()
      for (const image of await page.locator('img').all()) {
        if (!await image.isVisible()) continue
        await image.scrollIntoViewIfNeeded()
        await expect.poll(() => image.evaluate(img => (img as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
      }
      await page.evaluate(() => window.scrollTo(0, 0))
      await page.screenshot({ path: test.info().outputPath(`${route.startsWith('/match') ? 'match' : route.slice(1).replaceAll('/', '-')}-${width}.png`), fullPage: true })
    }
  }
  expect(errors).toEqual([])
})

test('reset clears both namespaces and returns the demo switch to off', async ({ page }) => {
  await enableDemo(page)
  await page.getByRole('button', { name: 'Очистить данные', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('обоих режимов')
  await page.getByRole('dialog').getByRole('button', { name: 'Очистить', exact: true }).click()
  await page.goto('/profile')
  await expect(page.getByRole('switch', { name: 'Демонстрационный режим' })).not.toBeChecked()
  await expect(page.getByRole('textbox', { name: 'Твоё имя' })).toHaveValue('')
  const values = await page.evaluate(() => ['poidem:demo:v1', 'poidem:simulation:v1'].map(key => JSON.parse(localStorage.getItem(key)!)))
  for (const state of values) {
    expect(state.profile).toBeNull()
    expect(state.ownPlans).toEqual([])
    expect(state.invites).toEqual([])
  }
})
