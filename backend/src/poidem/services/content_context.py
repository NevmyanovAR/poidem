"""Явные опасные предложения D47; нейтральные темы сами по себе не блокируются.

Это локальные проверяемые шаблоны, а не классификатор намерения или модератор.
Нельзя добавлять глобальное исключение «текст содержит слово лекция/не».
"""

import re
from dataclasses import dataclass

from poidem.services.content_language import phrase_variants
from poidem.services.content_places import PLACE_RULES


@dataclass(frozen=True)
class PhraseRule:
    code: str
    message: str
    patterns: tuple[str, ...]


_DRUG = (
    r"(?:наркотик(?:и|ов|ами|ам)?|наркотическ(?:ие|их)\s+веществ(?:а|ами)?|"
    r"меф(?:едрон)?(?:а|ом)?|кокаин(?:а|ом)?|героин(?:а|ом)?|амфетамин(?:а|ом)?|"
    r"метамфетамин(?:а|ом)?|марихуан(?:а|у|ы|ой)|гашиш(?:а|ем)?|"
    r"экстази|мдма|mdma|лсд|lsd|спайс(?:а|ы)?|наркотическ(?:ую|ая)\s+соль)"
)
_DEAL = (
    r"(?:продаю|продаем|продам|продадим|куплю|купим|покупаем|приобретем|"
    r"предлагаю|предлагаем|продажа|покупка|достану|достанем|закажем|закажу|распространяем|"
    r"употребим|употреблять|попробуем|покурим|нюхнем|употребляю)"
)
_GROUP = (
    r"(?:людей|люди|всех|мигрант(?:ов|ы|ам)|иностранц(?:ев|ы|ам)|евре(?:ев|и|ям)|"
    r"русск(?:их|ие|им)|украинц(?:ев|ы|ам)|армян(?:ам|е)?|мусульман(?:ам|е)?|"
    r"христиан(?:ам|е)?|геев|геи|геям|лесбиянок|лесбиянки|лесбиянкам|"
    r"женщин(?:ы|ам)?|мужчин(?:ы|ам)?|чернокожих|азиатов|цыган)"
)
_THREAT = r"(?:убью|убьем|зарежу|зарежем|изобью|изобьем|покалечу|покалечим|изнасилую)"
_PERSON = r"(?:тебя|вас|его|ее|их)"
_MODIFIER = r"(?:(?:точно|скоро|завтра|сегодня|лично|не\s+только)\s+)?"
RULES = (
    *(PhraseRule(*rule) for rule in PLACE_RULES),
    PhraseRule(
        "direct-insult",
        "Убери прямые оскорбления из текста плана",
        (
            r"(?:ты|вы|он|она)\s+(?:просто\s+|полный\s+|полная\s+)?"
            r"(?:туп(?:ой|ая|ые)|коз(?:ел|лы)|баран|овца|свинья|крыса|петух|шкура|чурка|чурбан)",
            r"(?:гребан(?:ый|ая)|жалк(?:ий|ая))\s+(?:козел|баран|овца|свинья|крыса|петух|чурка)",
        ),
    ),
    PhraseRule(
        "threat",
        "Убери угрозы и призывы к насилию",
        (
            r"(?:я\s+|мы\s+)?" + _PERSON + r"\s+" + _MODIFIER + _THREAT,
            _THREAT + r"\s+" + _MODIFIER + _PERSON,
            r"(?:давай|давайте|пойдем|предлагаю)\s+(?:вместе\s+)?(?:убивать|избивать|насиловать)\s+"
            + _GROUP,
            r"(?:убей|убейте|убивайте|бейте|избивайте|уничтожьте|насилуйте)\s+" + _GROUP,
            r"(?:подожжем|взорвем)\s+(?:школу|больницу|людей|дом\s+с\s+людьми)",
            r"(?:i\s+will|i\s+ll|we\s+will)\s+(?:kill|rape|stab)\s+you",
            r"(?:kill|rape)\s+(?:all\s+)?(?:jews|muslims|immigrants|women|men|gays)",
        ),
    ),
    PhraseRule(
        "hate",
        "Убери призывы к ненависти и унижение групп людей",
        (
            r"смерть\s+(?:всем\s+)?" + _GROUP,
            _GROUP + r"\s+(?:должны\s+умереть|не\s+люди|нужно\s+уничтожить|это\s+мусор)",
            r"(?:призываю|давайте|предлагаю)\s+ненавидеть\s+" + _GROUP,
        ),
    ),
    PhraseRule(
        "drugs",
        "В планах нельзя предлагать наркотики, их покупку или употребление",
        (
            _DEAL + r"\s+(?:(?:вместе|немного|дешево|чистый|чистого)\s+)?" + _DRUG,
            _DRUG + r"\s+(?:продаю|продам|в\s+наличии|с\s+доставкой|на\s+продажу)",
            r"(?:работа|вакансия|стань|работать)\s+(?:закладчиком|закладчика|кладменом|кладмена)",
            r"(?:покурим|покурить|курнем|курнуть)\s+(?:траву|анашу|шмаль|план)",
            r"(?:нюхнем|нюхать|занюхаем)\s+(?:кокс|дорожку|скорость)",
            r"(?:sell|selling|buy|buying|try|smoke|snort)\s+(?:cocaine|heroin|meth|mdma|weed|drugs)",
        ),
    ),
    PhraseRule(
        "sexual-services",
        "В планах нельзя предлагать платные сексуальные услуги",
        (
            r"(?:секс|интим|минет)\s+за\s+(?:деньги|оплату|вознаграждение|подарки|\d+)",
            r"(?:интимны[ех]|сексуальны[ех])\s+услуг(?:и|а|у)?",
            r"(?:предлагаю|оказываю|закажем|куплю|услуги)\s+(?:эскорт(?:а)?|проститутк[ауи])",
            r"(?:эскорт|проститутк[аи])\s+(?:за\s+деньги|с\s+выездом|на\s+заказ)",
            r"(?:sell|selling|buy|paid)\s+sex|sexual\s+services|escort\s+services",
        ),
    ),
    PhraseRule(
        "fraud",
        "В планах нельзя предлагать обман, кражу данных и мошеннические схемы",
        (
            r"(?:обманем|обмануть|обманываем|разведем|развести)\s+(?:людей|покупателей|на\s+деньги)",
            r"(?:украдем|украсть|продам|продаю)\s+(?:чужие\s+)?(?:пароли|данные\s+карт|данные\s+аккаунтов)",
            r"(?:оформим|возьмем|оформить)\s+кредит\s+на\s+чужое\s+имя",
            r"(?:создадим|сделаем|создать|запустим)\s+фишингов(?:ый\s+сайт|ую\s+рассылку)",
            r"(?:заработаем|заработок|заработать)\s+на\s+(?:скаме|мошенничестве|обмане)",
            r"(?:ищу|куплю|нужны)\s+дроп(?:ов|перов)|(?:работа|вакансия)\s+дроп(?:ом|пером)",
            r"(?:steal|selling|sell)\s+(?:passwords|stolen\s+credit\s+cards)",
        ),
    ),
)
_COMPILED = tuple(
    (rule, tuple(re.compile(r"(?<!\w)(?:" + pattern + r")(?!\w)") for pattern in rule.patterns))
    for rule in RULES
)
# Только ближайшее отрицание / непосредственное название произведения или темы.
# «Лекция о защите, а затем продам наркотики» не получает общего исключения.
_NEUTRAL_PREFIX = re.compile(
    r"(?:^|\s)(?:не\s+(?:(?:буду|будем|хочу|хотим|нужно|надо|стану|станем)\s+)?|"
    r"(?:фильм|книга|спектакль|песня|лекция|доклад|обсуждение|дискуссия)\s+"
    r"(?:(?:о|об|про|на\s+тему)\s+)?)$"
)


_TOPIC_PREFIX = re.compile(
    r"(?:^|\s)(?:без\s+|против\s+|не\s+(?:(?:продаю|продам|продавать|куплю|купим|"
    r"покупать|предлагаю|предлагать|будем|буду|хочу|хотим|нужно|надо|употреблять|"
    r"посещать|одобряю|поддерживаю)\s+){0,3}|"
    r"(?:лекция|доклад|дискуссия|обсуждение|обсудим|обсуждаем|история|статья|фильм|"
    r"книга|выставка|профилактика|лечение|значение|этимология|происхождение)\s+"
    r"(?:(?:о|об|про|на|тему|вреде|опасности|истории|последствиях|борьбе|продаже|"
    r"покупке|употреблении|употребления|слова|термина|понятия|с|от|против)\s+){0,5})$"
)
_TOPIC_CODES = frozenset(rule[0] for rule in PLACE_RULES)


def context_error(value: str) -> str | None:
    # Точки между буквами слова — маскировка, а не границы предложений.
    for clause in re.split(r"(?<!\w)[.!?;]|[.!?;](?!\w)|\n", value):
        for variant in phrase_variants(clause):
            for rule, patterns in _COMPILED:
                for pattern in patterns:
                    for match in pattern.finditer(variant):
                        if rule.code in _TOPIC_CODES and _TOPIC_PREFIX.search(
                            variant[: match.start()]
                        ):
                            continue
                        if not _NEUTRAL_PREFIX.search(variant[: match.start()]):
                            return rule.message
    return None
